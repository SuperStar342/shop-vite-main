SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS blade_non_prod_unit_price (
  id                bigint       NOT NULL COMMENT '主键',
  tenant_id         varchar(12)  DEFAULT '000000' COMMENT '租户',
  dispatch_type_code varchar(32) NOT NULL DEFAULT '' COMMENT '派工类型代号',
  dispatch_type_name varchar(64) NOT NULL DEFAULT '' COMMENT '派工类型名称',
  piece_type        varchar(32)  NOT NULL DEFAULT '' COMMENT '计件类型',
  control_attr      varchar(64)  DEFAULT '' COMMENT '控制属性',
  doc_name          varchar(128) DEFAULT '' COMMENT '单据名称',
  goods_code        varchar(64)  NOT NULL DEFAULT '' COMMENT '品号',
  goods_name        varchar(256) NOT NULL DEFAULT '' COMMENT '品名',
  std_attr          varchar(128) DEFAULT '' COMMENT '标准属性',
  unit_name         varchar(32)  DEFAULT '' COMMENT '单位名称',
  ratio_qty         decimal(18,4) DEFAULT 0 COMMENT '配料数量',
  piece_price       decimal(18,4) DEFAULT 0 COMMENT '计件单价',
  remark            varchar(512) DEFAULT '' COMMENT '备注',
  unit_code         varchar(32)  DEFAULT '' COMMENT '单位',
  resource_fixed_code varchar(64) DEFAULT '' COMMENT '资源固定代号',
  allow_edit_price  varchar(8)   NOT NULL DEFAULT '是' COMMENT '是否允许修改单价',
  create_user       bigint       DEFAULT NULL,
  create_dept       bigint       DEFAULT NULL,
  create_time       datetime     DEFAULT NULL,
  update_user       bigint       DEFAULT NULL,
  update_time       datetime     DEFAULT NULL,
  status            int          DEFAULT 1,
  is_deleted        int          DEFAULT 0,
  creator           varchar(64)  DEFAULT '' COMMENT '建立人',
  creator_code      varchar(64)  DEFAULT '' COMMENT '建立人代号',
  create_date       varchar(32)  DEFAULT '' COMMENT '建立日期文案',
  modifier          varchar(64)  DEFAULT '' COMMENT '修改人',
  modifier_code     varchar(64)  DEFAULT '' COMMENT '修改人代号',
  modify_date       varchar(32)  DEFAULT '' COMMENT '修改日期文案',
  PRIMARY KEY (id),
  KEY idx_npup_type (dispatch_type_code),
  KEY idx_npup_goods (goods_code),
  KEY idx_npup_tenant (tenant_id, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='非生产派工单价设置';

